#!/usr/bin/env python3
"""Generate a complete, path-labelled native source bundle for review."""
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    explicit = ["Package.swift", "Info.plist", "MD3Agent.entitlements", "README.md",
                "docs/macos-port.md", "scripts/package-macos.sh",
                "scripts/VerifyPortable.swift", "scripts/export-native-source.py"]
    paths = [root / name for name in explicit]
    for directory in ["Sources", "Tests", ".github/workflows"]:
        paths.extend(path for path in (root / directory).rglob("*") if path.is_file())
    suffix_languages = {".swift": "swift", ".plist": "xml", ".entitlements": "xml",
                        ".h": "c", ".yml": "yaml", ".sh": "bash", ".py": "python",
                        ".md": "markdown"}
    sections = ["# native source bundle\n\n"
                "generated by `python3 scripts/export-native-source.py`. "
                "complete files follow; no source content is abbreviated.\n"]
    for path in sorted(set(paths)):
        content = path.read_text(encoding="utf-8")
        longest = max((len(part) for part in content.split("\n") if part and set(part) == {"`"}), default=0)
        fence = "`" * max(4, longest + 1)
        language = suffix_languages.get(path.suffix, "text")
        sections.append(f"\n## `{path.relative_to(root)}`\n\n{fence}{language}\n{content.rstrip()}\n{fence}\n")
    destination = root / "docs/native-source.md"
    destination.write_text("".join(sections), encoding="utf-8")
    print(f"exported {len(set(paths))} complete files to {destination.relative_to(root)}")


if __name__ == "__main__":
    main()
